// @ts-check
// One flat config for the whole monorepo. Formatting is Prettier's job, so no style rules here.
import eslint from '@eslint/js';
import angular from 'angular-eslint';
import { defineConfig, globalIgnores } from 'eslint/config';
import tseslint from 'typescript-eslint';

// Colours come from the tokens in _tokens.scss (BLUEPRINT §8.1). Stylelint checks stylesheets;
// these selectors catch hex values in inline component styles and template attributes.
const hexColour = String.raw`/#[0-9a-fA-F]{3,8}\b/`;
const noHexMessage = 'Use a colour token (var(--ss-…)) from _tokens.scss instead of a hex value.';

export default defineConfig(
  globalIgnores([
    '**/dist/',
    '**/.angular/',
    '**/coverage/',
    '**/.wrangler/',
    'apps/api/public/', // the web build, copied in by scripts/copy-web-build.mjs
    'apps/api/worker-configuration.d.ts', // generated by `wrangler types`
    'apps/bot/worker-configuration.d.ts',
    'docs/',
  ]),
  {
    files: ['**/*.ts'],
    extends: [eslint.configs.recommended, tseslint.configs.recommended, tseslint.configs.stylistic],
  },
  {
    // packages/core is plain TypeScript shared by the app, the Worker and the scripts (BLUEPRINT §3),
    // and it never reads the clock: the app passes `today` in from ClockService (CLAUDE.md).
    files: ['packages/core/**/*.ts'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['@angular/*', 'dexie', 'hono', 'hono/*', 'cloudflare:*', 'node:*'],
              message: 'packages/core is pure TypeScript: no framework, storage or runtime APIs.',
            },
          ],
        },
      ],
      'no-restricted-syntax': [
        'error',
        {
          selector: "NewExpression[callee.name='Date'][arguments.length=0]",
          message: 'Take `today` as a parameter instead of reading the clock.',
        },
        {
          selector: "CallExpression[callee.object.name='Date'][callee.property.name='now']",
          message: 'Take `today` as a parameter instead of reading the clock.',
        },
        {
          // `{ z }` is an object holding all of Zod, every locale's messages included (about 450 kB minified in the
          // app's storage chunk); a namespace import lets the bundler keep only what's used (under 100 kB).
          selector: "ImportDeclaration[source.value='zod'] > ImportSpecifier[imported.name='z']",
          message: "Use `import * as z from 'zod'`, which bundlers can tree-shake.",
        },
      ],
    },
  },
  {
    files: ['apps/web/**/*.ts'],
    extends: [angular.configs.tsRecommended],
    processor: angular.processInlineTemplates,
    rules: {
      '@angular-eslint/directive-selector': [
        'error',
        { type: 'attribute', prefix: 'ss', style: 'camelCase' },
      ],
      '@angular-eslint/component-selector': [
        'error',
        { type: 'element', prefix: 'ss', style: 'kebab-case' },
      ],
      'no-restricted-syntax': [
        'error',
        {
          selector: `Property[key.name='styles'] :matches(Literal[value=${hexColour}], TemplateElement[value.raw=${hexColour}])`,
          message: noHexMessage,
        },
      ],
    },
  },
  {
    // The repositories in core/storage/ are the only way into IndexedDB (BLUEPRINT §11.1), so the app lock (M6.10)
    // can wrap them without changing a page.
    files: ['apps/web/**/*.ts'],
    ignores: ['apps/web/src/app/core/storage/**'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['dexie', 'dexie/*'],
              message: 'Only the repositories in core/storage/ use Dexie (BLUEPRINT §11.1).',
            },
          ],
        },
      ],
    },
  },
  {
    files: ['apps/web/**/*.html'],
    extends: [angular.configs.templateRecommended, angular.configs.templateAccessibility],
    rules: {
      'no-restricted-syntax': [
        'error',
        { selector: `TextAttribute[name!='href'][value=${hexColour}]`, message: noHexMessage },
      ],
    },
  },
  {
    // index.html's theme-color metas (M10.6) are read before any CSS, so they hold the top bar's colours as hex;
    // apps/api/test/web-manifest.spec.ts keeps them equal to _tokens.scss's.
    files: ['apps/web/src/index.html'],
    rules: { 'no-restricted-syntax': 'off' },
  },
);
